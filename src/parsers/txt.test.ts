import { describe, expect, it } from "vitest";
import { parseFile, parseText } from "./index";
import { encodeCp1251Basic, encodeSingleByte, fileFrom } from "./test-fixtures";
import { detectToc, parseTxt, splitPlainText } from "./txt";

// Старый lib.ru: жёсткий перенос ~70 знаков, абзац начинается с отступа, переносы слов
const LIBRU = [
	"                              ЧАСТЬ ПЕРВАЯ",
	"",
	"                              ГЛАВА 1",
	"",
	"     Утро выдалось холодным и ясным. Иван вышел из дома рано, когда на",
	"улице ещё никого не было, и долго стоял у калитки, глядя на пустую до-",
	"рогу и на серые крыши соседних домов, мокрые после ночного дождя.",
	"     Потом он вернулся в дом, сел за стол и написал письмо брату, ко-",
	"торый жил далеко на севере и давно не присылал никаких вестей домой.",
	"     - Ты куда собрался? - спросила мать, выглянув из кухни с полотенцем.",
	"     - На станцию, - ответил он и надел старую отцовскую шапку и пальто.",
	"",
	"                              ГЛАВА 2",
	"",
	"     Станция встретила его шумом и запахом угля. Поезд опаздывал на час,",
	"и Иван успел выпить чаю в буфете, где сидели знакомые ему мужики из",
	"соседней деревни и громко спорили о ценах на хлеб и на лошадей тоже.",
].join("\r\n");

// Проект Гутенберг: перенос строк, абзацы через пустую строку
const GUTENBERG = [
	"Глава первая",
	"",
	"Было тихо. Над рекой стоял туман, и лодки у берега едва угадывались в",
	"молочной белизне раннего утра, которое обещало долгий жаркий день.",
	"",
	"Старик спустился к воде, отвязал лодку и оттолкнулся веслом от бере-",
	"га, не оглядываясь на деревню, где уже начинали кричать петухи.",
	"",
	"Глава вторая",
	"",
	"Вечером он вернулся с полной лодкой рыбы и долго сидел на крыльце,",
	"слушая, как в саду шумит ветер и падают в траву спелые яблоки.",
].join("\n");

describe("TXT", () => {
	it("cp1251 с жёстким переносом и отступами (lib.ru)", () => {
		const book = parseTxt(encodeCp1251Basic(LIBRU), "Повесть.txt");
		expect(book.title).toBe("Повесть");
		expect(book.format).toBe("txt");
		expect(book.paragraphs).toEqual([
			"ЧАСТЬ ПЕРВАЯ",
			"ГЛАВА 1",
			"Утро выдалось холодным и ясным. Иван вышел из дома рано, когда на улице ещё никого не было, и долго стоял у калитки, глядя на пустую дорогу и на серые крыши соседних домов, мокрые после ночного дождя.",
			"Потом он вернулся в дом, сел за стол и написал письмо брату, который жил далеко на севере и давно не присылал никаких вестей домой.",
			"- Ты куда собрался? - спросила мать, выглянув из кухни с полотенцем.",
			"- На станцию, - ответил он и надел старую отцовскую шапку и пальто.",
			"ГЛАВА 2",
			"Станция встретила его шумом и запахом угля. Поезд опаздывал на час, и Иван успел выпить чаю в буфете, где сидели знакомые ему мужики из соседней деревни и громко спорили о ценах на хлеб и на лошадей тоже.",
		]);
		expect(book.toc).toEqual([
			{ title: "ЧАСТЬ ПЕРВАЯ", level: 0, paragraph: 0 },
			{ title: "ГЛАВА 1", level: 1, paragraph: 1 },
			{ title: "ГЛАВА 2", level: 1, paragraph: 6 },
		]);
	});

	it("koi8-r с абзацами через пустую строку", () => {
		const book = parseTxt(encodeSingleByte(GUTENBERG, "koi8-r"), "river.txt");
		expect(book.paragraphs).toEqual([
			"Глава первая",
			"Было тихо. Над рекой стоял туман, и лодки у берега едва угадывались в молочной белизне раннего утра, которое обещало долгий жаркий день.",
			"Старик спустился к воде, отвязал лодку и оттолкнулся веслом от берега, не оглядываясь на деревню, где уже начинали кричать петухи.",
			"Глава вторая",
			"Вечером он вернулся с полной лодкой рыбы и долго сидел на крыльце, слушая, как в саду шумит ветер и падают в траву спелые яблоки.",
		]);
		expect(book.toc).toEqual([
			{ title: "Глава первая", level: 0, paragraph: 0 },
			{ title: "Глава вторая", level: 0, paragraph: 3 },
		]);
	});

	it("одна строка — один абзац, если текст без переносов", () => {
		const text = "Первый абзац целиком в одной длинной строке, как пишут современные редакторы текста без всякого переноса строк внутри абзаца.\nВторой.\n\n\nТретий абзац.";
		expect(splitPlainText(text)).toEqual([
			"Первый абзац целиком в одной длинной строке, как пишут современные редакторы текста без всякого переноса строк внутри абзаца.",
			"Второй.",
			"Третий абзац.",
		]);
	});

	it("заголовки: не путает начало фразы с главой", () => {
		const toc = detectToc(["Глава семьи сказал своё слово.", "Часть меня хотела уйти.", "Пролог", "Глава 3. Дорога", "IV", "Chapter Seven", "Part of me"]);
		expect(toc.map((e) => e.paragraph)).toEqual([2, 3, 4, 5]);
	});

	it("напечатанное оглавление убирается", () => {
		const text = ["Содержание", "Глава 1. Начало", "Глава 2. Дорога", "Глава 3. Конец", "", "Глава 1. Начало", "Текст первой главы.", "Глава 2. Дорога", "Текст второй главы.", "Глава 3. Конец", "Текст третьей главы."].join("\n");
		const book = parseText(text, "Тест");
		expect(book.paragraphs[0]).toBe("Глава 1. Начало");
		expect(book.paragraphs).toHaveLength(6);
		expect(book.toc.map((e) => e.paragraph)).toEqual([0, 2, 4]);
	});

	it("вставленный текст: формат text и название по первым словам", () => {
		const book = parseText("Однажды весною, в час небывало жаркого заката, в Москве, на Патриарших прудах, появились два гражданина.");
		expect(book.format).toBe("text");
		expect(book.title.startsWith("Однажды весною")).toBe(true);
		expect(book.title.length).toBeLessThanOrEqual(61);
		expect(parseText("Текст", "Моё название").title).toBe("Моё название");
	});

	it("parseFile определяет TXT и по содержимому", async () => {
		const book = await parseFile(fileFrom(encodeCp1251Basic("Привет, мир. Это проверка простого текста."), "заметка"));
		expect(book.format).toBe("txt");
		expect(book.paragraphs).toEqual(["Привет, мир. Это проверка простого текста."]);
	});
});
